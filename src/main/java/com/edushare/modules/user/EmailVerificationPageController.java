package com.edushare.modules.user;

import org.springframework.http.MediaType;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Same email verification page for students and administrators. The backend determines the correct
 * sign-in path AFTER verification.
 */
@RestController
public class EmailVerificationPageController {

    @GetMapping(value = "/verify-email", produces = MediaType.TEXT_HTML_VALUE)
    public String page() {
        return "<!DOCTYPE html>\n"
                   + "<html lang=\"en\">\n"
                   + "<head>\n"
                   + "  <meta charset=\"UTF-8\">\n"
                   + "  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
                   + "  <title>Verify your email | EduShare</title>\n"
                   + "  <style>\n"
                   + "    * { box-sizing: border-box; }\n"
                   + "    [hidden] { display:none !important; }\n"
                   + "    body { margin:0; min-height:100vh; font:16px/1.6"
                   + " system-ui,Arial,sans-serif;\n"
                   + "           background:#f3f6ff; color:#192744; display:grid;"
                   + " place-items:center; padding:24px; }\n"
                   + "    main { width:min(100%,480px); padding:38px 34px; border-radius:20px;\n"
                   + "           background:white; text-align:center; box-shadow:0 14px 40px"
                   + " #14295713; }\n"
                   + "    .brand { font-size:30px; letter-spacing:-.5px; color:#293d86;"
                   + " font-weight:800; margin:0 0 20px; }\n"
                   + "    h1 { font-size:24px; line-height:1.3; margin:0 0 15px; color:#182643; }\n"
                   + "    p { color:#64718c; margin:10px 0 22px; }\n"
                   + "    .notice { background:#f4f7fe; color:#506085; border-radius:10px;\n"
                   + "              padding:11px 14px; margin:20px 0; font-size:14px; }\n"
                   + "    button, a.action { display:block; width:100%; max-width:280px;"
                   + " margin:10px auto;\n"
                   + "        border-radius:10px; padding:12px 18px; font:600 15px"
                   + " system-ui,Arial,sans-serif;\n"
                   + "        text-align:center; cursor:pointer; text-decoration:none; }\n"
                   + "    button { background:#293d86; color:white; border:1px solid #293d86; }\n"
                   + "    button:disabled { opacity:.55; cursor:default; }\n"
                   + "    a.action { border:1px solid #293d86; color:#293d86; background:white; }\n"
                   + "    .success { color:#14643a; } .error { color:#a12236; }\n"
                   + "    footer { border-top:1px solid #e7ebf3; margin-top:26px;"
                   + " padding-top:20px;\n"
                   + "             color:#7a859b; font-size:13px; }\n"
                   + "  </style>\n"
                   + "</head>\n"
                   + "<body>\n"
                   + "  <main>\n"
                   + "    <div class=\"brand\">EduShare</div>\n"
                   + "    <h1>Verify Your Email Address</h1>\n"
                   + "    <p id=\"message\" role=\"status\" aria-live=\"polite\">\n"
                   + "      Click below to complete your EduShare account verification.\n"
                   + "    </p>\n"
                   + "    <div class=\"notice\">This verification link is valid for a limited time"
                   + " and can only be used once.</div>\n"
                   + "    <button id=\"verifyButton\" type=\"button\">Verify My Email</button>\n"
                   + "    <a class=\"action\" id=\"signInLink\" href=\"/login\" hidden>Back to Sign"
                   + " In</a>\n"
                   + "    <footer>The owner of the email address verifies their own account.\n"
                   + "      Administrators do not need to verify student accounts"
                   + " manually.</footer>\n"
                   + "  </main>\n"
                   + "  <script>\n"
                   + "    (function () {\n"
                   + "      const message = document.getElementById('message');\n"
                   + "      const button = document.getElementById('verifyButton');\n"
                   + "      const link = document.getElementById('signInLink');\n"
                   + "      const token = new URLSearchParams(location.search).get('token');\n"
                   + "      if (!token) {\n"
                   + "        message.textContent = 'Verification token is missing. Open the link"
                   + " sent to your email.';\n"
                   + "        message.className = 'error'; button.disabled = true;\n"
                   + "        link.hidden = false; return;\n"
                   + "      }\n"
                   + "      button.addEventListener('click', async function () {\n"
                   + "        button.disabled = true;\n"
                   + "        message.className = '';\n"
                   + "        message.textContent = 'Verifying your email...';\n"
                   + "        try {\n"
                   + "          const response = await fetch('/api/email-auth/verify', {\n"
                   + "            method: 'POST',\n"
                   + "            headers: { 'Content-Type': 'application/json' },\n"
                   + "            body: JSON.stringify({ token: token }),\n"
                   + "            credentials: 'same-origin'\n"
                   + "          });\n"
                   + "          const data = await response.json().catch(() => ({}));\n"
                   + "          if (!response.ok) throw new Error(data.error || 'Verification"
                   + " failed. Please request a new link.');\n"
                   + "          message.textContent = 'Email verified successfully! You can now"
                   + " sign in.';\n"
                   + "          message.className = 'success';\n"
                   + "          button.hidden = true;\n"
                   + "          // This value comes from the backend, not from an untrusted URL"
                   + " role parameter.\n"
                   + "          link.href = data.signInPath === '/admin/login' ? '/admin/login' :"
                   + " '/login';\n"
                   + "          link.textContent = data.signInPath === '/admin/login' ? 'Admin Sign"
                   + " In' : 'Student Sign In';\n"
                   + "          link.hidden = false;\n"
                   + "          // Remove the used token from browser history.\n"
                   + "          history.replaceState(null, '', '/verify-email');\n"
                   + "        } catch (err) {\n"
                   + "          message.textContent = err.message;\n"
                   + "          message.className = 'error';\n"
                   + "          button.disabled = false;\n"
                   + "        }\n"
                   + "      });\n"
                   + "    }());\n"
                   + "  </script>\n"
                   + "</body>\n"
                   + "</html>\n";
    }
}
